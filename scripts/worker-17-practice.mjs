// ─── HTML Generator ──────────────────────────────────────────────────────────
function generatePracticeHTML(entry) {
  const { blockId, questions, reflect } = entry;
  const qCount = questions.length;
  const estMin = Math.max(3, qCount * 2);

  let questionsHTML = '';
  questions.forEach((q, i) => {
    const qId = `${blockId}-q${i + 1}`;
    questionsHTML += `
    <li class="practice-question" data-q-id="${qId}">
      <p class="practice-question-text type-body">${q.q}</p>
      <details class="practice-answer">
        <summary class="practice-answer-summary type-ui-label">
          <span class="practice-answer-icon" aria-hidden="true">\u2193</span>
          <span>اكشف الإجابة</span>
        </summary>
        <div class="practice-answer-body type-body">${q.a}</div>
      </details>
      <button class="practice-tried-btn type-button" type="button" data-q-id="${qId}" aria-pressed="false">
        <span class="practice-tried-icon" aria-hidden="true"></span>
        <span class="practice-tried-label">حاولت</span>
      </button>
    </li>`;
  });

  return `
<section class="block-practice" data-practice-for="${blockId}" aria-label="تمارين استدعاء نشط">
  <header class="block-practice-h">
    <span class="block-practice-eyebrow type-eyebrow">تمرين استدعاء</span>
    <h4 class="block-practice-title type-display-h">تحقّق من فهمك</h4>
    <span class="block-practice-meta type-num"><span data-practice-count="${qCount}">${qCount} أسئلة</span> · <span data-practice-est="${estMin}">~${estMin} دقائق</span></span>
  </header>
  <ol class="practice-questions">${questionsHTML}
  </ol>
  <footer class="block-practice-reflect">
    <h5 class="block-practice-reflect-h type-eyebrow">تأمّل ختامي</h5>
    <p class="block-practice-reflect-prompt type-quote-literary">${reflect}</p>
    <textarea class="block-practice-reflect-input" data-reflect-for="${blockId}" placeholder="اكتب جوابك هنا (يُحفَظ محلياً، لا يُرسل لأي خادم)" rows="3" maxlength="500"></textarea>
    <div class="block-practice-reflect-meta type-num"><span data-reflect-count="0">0</span> / 500 حرف</div>
  </footer>
</section>`;
}


// ─── Injection Logic ─────────────────────────────────────────────────────────
function inject() {
  let html = readFileSync(HTML_PATH, 'utf-8');
  let injected = 0;
  let skipped = 0;

  for (const entry of PRACTICE_MAP) {
    const { blockId } = entry;

    // Idempotent guard: skip if already injected
    if (html.includes(`data-practice-for="${blockId}"`)) {
      skipped++;
      continue;
    }

    // Find the block by data-block-id — look for the closing tag of its container
    // Strategy: find the line with data-block-id="<blockId>" then find the end of
    // that block's container. Insert practice section AFTER:
    //   1. block-pitfalls (if present)
    //   2. block-takeaways (if present)
    //   3. the block's closing tag
    
    // Find the block occurrence
    const blockAttrRegex = new RegExp(`data-block-id="${blockId}"`, 'g');
    const match = blockAttrRegex.exec(html);
    if (!match) {
      console.warn(`[SKIP] Block ${blockId} not found in HTML.`);
      continue;
    }

    // Find the position after this block's siblings (pitfalls/takeaways)
    // Look for the next data-block-id or </section class="page" after this one
    const startPos = match.index;
    
    // Check if there's a pitfalls section for this block
    const pitfallsMarker = `data-pitfalls-for="${blockId}"`;
    const pitfallsIdx = html.indexOf(pitfallsMarker, startPos);
    
    let insertPos;
    
    if (pitfallsIdx !== -1 && pitfallsIdx - startPos < 15000) {
      // Insert after the closing </details> of pitfalls
      const closingDetails = html.indexOf('</details>', pitfallsIdx);
      if (closingDetails !== -1) {
        insertPos = closingDetails + '</details>'.length;
      }
    }
    
    if (!insertPos) {
      // Check for block-takeaways after this block
      const takeawaysCheck = html.indexOf(`<!--takeaways-for:${blockId}-->`, startPos);
      if (takeawaysCheck !== -1 && takeawaysCheck - startPos < 10000) {
        // Find closing </ul> after takeaways
        const closingUl = html.indexOf('</ul>', takeawaysCheck);
        if (closingUl !== -1) {
          insertPos = closingUl + '</ul>'.length;
        }
      }
    }

    if (!insertPos) {
      // Fallback: find the closing tag of the block's element
      // The block is usually a <div>, <section>, <article>, or similar
      // Find the opening tag character
      const tagStart = html.lastIndexOf('<', startPos);
      const tagEnd = html.indexOf('>', startPos);
      const openingTag = html.slice(tagStart, tagEnd + 1);
      
      // Determine the tag name
      const tagNameMatch = openingTag.match(/^<(\w+)/);
      if (!tagNameMatch) {
        console.warn(`[SKIP] Cannot determine tag for block ${blockId}`);
        continue;
      }
      const tagName = tagNameMatch[1];
      
      // Find the matching closing tag - simple approach for well-formed HTML
      // Count nested tags of the same type
      let depth = 1;
      let searchPos = tagEnd + 1;
      const openRegex = new RegExp(`<${tagName}[\\s>]`, 'gi');
      const closeRegex = new RegExp(`</${tagName}>`, 'gi');
      
      // Simpler approach: find all open/close of this tag type after our position
      let closePos = -1;
      while (depth > 0 && searchPos < html.length) {
        const nextOpen = html.indexOf(`<${tagName}`, searchPos);
        const nextClose = html.indexOf(`</${tagName}>`, searchPos);
        
        if (nextClose === -1) break;
        
        if (nextOpen !== -1 && nextOpen < nextClose) {
          // Check it's actually an opening tag (not a substring)
          const charAfter = html[nextOpen + tagName.length + 1];
          if (charAfter === ' ' || charAfter === '>' || charAfter === '\n' || charAfter === '\r') {
            depth++;
          }
          searchPos = nextOpen + 1;
        } else {
          depth--;
          if (depth === 0) {
            closePos = nextClose + `</${tagName}>`.length;
          }
          searchPos = nextClose + 1;
        }
      }
      
      if (closePos === -1) {
        console.warn(`[SKIP] Cannot find closing tag for block ${blockId}`);
        continue;
      }
      insertPos = closePos;
    }

    // Insert the practice section
    const practiceHTML = generatePracticeHTML(entry);
    html = html.slice(0, insertPos) + '\n' + practiceHTML + html.slice(insertPos);
    injected++;
  }

  writeFileSync(HTML_PATH, html, 'utf-8');
  console.log(`\n✅ Practice injection complete.`);
  console.log(`   Injected: ${injected}`);
  console.log(`   Skipped (already exist): ${skipped}`);
  console.log(`   Total in map: ${PRACTICE_MAP.length}`);
}

inject();
