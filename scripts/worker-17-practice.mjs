// ─── Injection Logic ──────────────────────────────────────────────────────────

function inject() {
  let html = readFileSync(HTML_PATH, 'utf8');
  let injected = 0;
  let skipped = 0;

  // Process in REVERSE order to preserve line indices
  const entries = [...PRACTICE_MAP].reverse();

  for (const entry of entries) {
    const { blockId } = entry;

    // Idempotency guard
    if (html.includes(`data-practice-for="${blockId}"`)) {
      skipped++;
      continue;
    }

    // Find insertion point: after pitfalls for this block, or after takeaways, or after the block's closing tag
    // Strategy: find the block by data-block-id, then find the best insertion point after it

    const blockPattern = new RegExp(`data-block-id="${blockId.replace(/[-]/g, '\\-')}"`, 'g');
    let blockMatch;
    let lastBlockIdx = -1;

    // Find last occurrence of this block-id (the block element itself)
    while ((blockMatch = blockPattern.exec(html)) !== null) {
      lastBlockIdx = blockMatch.index;
    }

    if (lastBlockIdx === -1) {
      console.warn(`⚠️  Block ${blockId} not found in HTML — skipping.`);
      skipped++;
      continue;
    }

    // Find insertion point after the block:
    // Priority 1: after </details> of block-pitfalls for this block
    // Priority 2: after </ul> of block-takeaways following this block
    // Priority 3: after the block's closing tag

    let insertIdx = -1;

    // Check for pitfalls for this block
    const pitfallsMarker = `data-pitfalls-for="${blockId}"`;
    const pitfallsIdx = html.indexOf(pitfallsMarker, lastBlockIdx);
    if (pitfallsIdx !== -1 && pitfallsIdx - lastBlockIdx < 5000) {
      // Find closing </details> after pitfalls
      const closingDetails = html.indexOf('</details>', pitfallsIdx);
      if (closingDetails !== -1) {
        insertIdx = closingDetails + '</details>'.length;
      }
    }

    // If no pitfalls, look for block-takeaways after this block
    if (insertIdx === -1) {
      // Look for takeaways within 3000 chars after block
      const afterBlock = html.substring(lastBlockIdx, lastBlockIdx + 3000);
      const takeawayMatch = afterBlock.match(/class="block-takeaways"/);
      if (takeawayMatch) {
        const takeawayStart = lastBlockIdx + takeawayMatch.index;
        const closingUl = html.indexOf('</ul>', takeawayStart);
        if (closingUl !== -1) {
          insertIdx = closingUl + '</ul>'.length;
        }
      }
    }

    // If no takeaways either, insert after the block element's closing tag
    if (insertIdx === -1) {
      // Find the opening tag containing data-block-id
      const tagStart = html.lastIndexOf('<', lastBlockIdx);
      // Determine the tag name
      const tagNameMatch = html.substring(tagStart, tagStart + 50).match(/<(\w+)/);
      if (tagNameMatch) {
        const tagName = tagNameMatch[1];
        // Find matching closing tag (simple search — works for most blocks)
        let searchFrom = lastBlockIdx;
        let depth = 1;
        const openRe = new RegExp(`<${tagName}[\\s>]`, 'g');
        const closeRe = new RegExp(`</${tagName}>`, 'g');

        // Simple approach: find next closing tag of same type within 5000 chars
        const closeIdx = html.indexOf(`</${tagName}>`, lastBlockIdx + 10);
        if (closeIdx !== -1 && closeIdx - lastBlockIdx < 8000) {
          insertIdx = closeIdx + `</${tagName}>`.length;
        }
      }
    }

    if (insertIdx === -1) {
      console.warn(`⚠️  Could not find insertion point for ${blockId} — skipping.`);
      skipped++;
      continue;
    }

    // Insert practice section
    const practiceHTML = generatePracticeHTML(entry);
    html = html.slice(0, insertIdx) + '\n' + practiceHTML + html.slice(insertIdx);
    injected++;
  }

  writeFileSync(HTML_PATH, html, 'utf8');
  console.log(`\n✅ Practice injection complete:`);
  console.log(`   Injected: ${injected}`);
  console.log(`   Skipped:  ${skipped}`);
  console.log(`   Total in map: ${PRACTICE_MAP.length}`);
}

inject();
